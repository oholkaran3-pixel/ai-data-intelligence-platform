import os
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors
import pandas as pd
from typing import Dict, Any, List

class MultiFormatReportGenerator:
    """
    Generates professional PDF and multi-tab Excel reports from live dataset analyses.
    """

    @staticmethod
    def generate_excel_report(df: pd.DataFrame, quality_summary: Dict[str, Any], output_path: str) -> str:
        wb = openpyxl.Workbook()
        
        # Sheet 1: Executive KPI & Quality Summary
        ws1 = wb.active
        ws1.title = "Executive Summary"
        
        # Styles
        header_fill = PatternFill(start_color="1E3A8A", end_color="1E3A8A", fill_type="solid")
        header_font = Font(name="Calibri", size=14, bold=True, color="FFFFFF")
        title_font = Font(name="Calibri", size=16, bold=True, color="1E3A8A")
        sub_font = Font(name="Calibri", size=11, bold=True)
        
        ws1["A1"] = "AI Data Intelligence — Dataset Audit & Profiling Report"
        ws1["A1"].font = title_font
        
        ws1["A3"] = "Metric"
        ws1["B3"] = "Value"
        ws1["A3"].fill = header_fill
        ws1["B3"].fill = header_fill
        ws1["A3"].font = header_font
        ws1["B3"].font = header_font

        metrics = [
            ("Data Quality Score", f"{quality_summary.get('score', 100)}%"),
            ("Data Grade", str(quality_summary.get('grade', 'N/A'))),
            ("Total Record Count", str(quality_summary.get('total_rows', len(df)))),
            ("Total Columns", str(quality_summary.get('total_columns', len(df.columns)))),
            ("Missing Cell Count", str(quality_summary.get('total_missing_cells', 0))),
            ("Duplicate Records", str(quality_summary.get('duplicate_rows', 0))),
            ("Outliers Detected", str(quality_summary.get('total_outliers_detected', 0)))
        ]

        for i, (k, v) in enumerate(metrics, start=4):
            ws1[f"A{i}"] = k
            ws1[f"B{i}"] = v
            ws1[f"A{i}"].font = sub_font
            
        ws1.column_dimensions["A"].width = 28
        ws1.column_dimensions["B"].width = 24

        # Sheet 2: Processed Dataset (up to 10,000 rows preview in Excel)
        ws2 = wb.create_sheet(title="Cleaned Data")
        
        # Add columns
        cols = list(df.columns)
        for col_num, col_name in enumerate(cols, 1):
            cell = ws2.cell(row=1, column=col_num, value=str(col_name))
            cell.font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
            cell.fill = PatternFill(start_color="2563EB", end_color="2563EB", fill_type="solid")

        # Add data
        for row_idx, row_data in enumerate(df.head(10000).values, 2):
            for col_idx, value in enumerate(row_data, 1):
                val_clean = str(value) if pd.notnull(value) else ""
                ws2.cell(row=row_idx, column=col_idx, value=val_clean)

        wb.save(output_path)
        return output_path

    @staticmethod
    def generate_pdf_report(title: str, dataset_name: str, quality_summary: Dict[str, Any], output_path: str) -> str:
        doc = SimpleDocTemplate(output_path, pagesize=letter, rightMargin=40, leftMargin=40, topMargin=40, bottomMargin=40)
        styles = getSampleStyleSheet()
        
        title_style = ParagraphStyle(
            'ReportTitle',
            parent=styles['Heading1'],
            fontSize=22,
            textColor=colors.HexColor('#1E293B'),
            spaceAfter=14
        )
        body_style = ParagraphStyle(
            'ReportBody',
            parent=styles['Normal'],
            fontSize=11,
            textColor=colors.HexColor('#334155'),
            spaceAfter=8
        )
        
        story = []
        story.append(Paragraph(title, title_style))
        story.append(Paragraph(f"<b>Dataset:</b> {dataset_name} | <b>Generated by:</b> AI Data Intelligence Platform", body_style))
        story.append(Spacer(1, 15))
        
        # Summary Table
        table_data = [
            ["Metric", "Result"],
            ["Data Quality Score", f"{quality_summary.get('score', 100)}%"],
            ["Quality Integrity Grade", str(quality_summary.get('grade', 'Excellent'))],
            ["Total Rows", f"{quality_summary.get('total_rows', 0):,}"],
            ["Total Columns", str(quality_summary.get('total_columns', 0))],
            ["Duplicate Records", str(quality_summary.get('duplicate_rows', 0))],
            ["Outlier Count", str(quality_summary.get('total_outliers_detected', 0))]
        ]
        
        t = Table(table_data, colWidths=[240, 240])
        t.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#2563EB')),
            ('TEXTCOLOR', (0,0), (-1,0), colors.whitesmoke),
            ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
            ('FONTSIZE', (0,0), (-1,0), 12),
            ('BOTTOMPADDING', (0,0), (-1,0), 8),
            ('GRID', (0,0), (-1,-1), 1, colors.HexColor('#CBD5E1')),
            ('ROWBACKGROUNDS', (0,1), (-1,-1), [colors.white, colors.HexColor('#F8FAFC')])
        ]))
        story.append(t)
        story.append(Spacer(1, 20))
        
        story.append(Paragraph("<b>Executive Summary & Methodology:</b>", styles['Heading2']))
        story.append(Paragraph("This dataset underwent automated multi-pass verification including missing value scanning, duplicate identification, and interquartile range (IQR) outlier screening. Data integrity is confirmed for advanced statistical and machine learning modeling.", body_style))
        
        doc.build(story)
        return output_path
